/** Orden fijo de ficha técnica (catálogo). */
function ft(
  modelo: string,
  precio: string,
  vigencia: string,
  motor: string,
  transmision: string,
  potencia: string,
  consumo: string,
  seguridad: string,
  autonomia: string,
): FichaTecnicaRow[] {
  return [
    { label: "Modelo", value: modelo },
    { label: "Precio", value: precio },
    { label: "Vigencia", value: vigencia },
    { label: "Tipo de motor", value: motor },
    { label: "Transmisión", value: transmision },
    { label: "Potencia", value: potencia },
    { label: "Consumo", value: consumo },
    { label: "Seguridad", value: seguridad },
    { label: "Autonomía", value: autonomia },
  ];
}

interface VarianteFicha {
  nombre: string;
  precio: string;
  vigencia: string;
  motor: string;
  transmision: string;
  potencia: string;
  consumo: string;
  seguridad: string;
  autonomia: string;
}

/** Una sola ficha para el mismo auto con versiones (nafta, híbrido, Plus, etc.). */
function ftVariantes(variantes: VarianteFicha[]): FichaTecnicaRow[] {
  const campo = (key: keyof Omit<VarianteFicha, "nombre">) => {
    const values = variantes.map((v) => v[key]);
    if (new Set(values).size === 1) return values[0];
    return variantes.map((v) => `${v.nombre}: ${v[key]}`).join(" · ");
  };

  return ft(
    variantes.map((v) => v.nombre).join(" · "),
    campo("precio"),
    campo("vigencia"),
    campo("motor"),
    campo("transmision"),
    campo("potencia"),
    campo("consumo"),
    campo("seguridad"),
    campo("autonomia"),
  );
}

function fichaPendiente(nombre: string): FichaTecnicaRow[] {
  return ft(
    nombre,
    "Sin precio de referencia",
    "Por confirmar",
    "Por confirmar",
    "Por confirmar",
    "Por confirmar",
    "Por confirmar",
    "Por confirmar",
    "Por confirmar",
  );
}

